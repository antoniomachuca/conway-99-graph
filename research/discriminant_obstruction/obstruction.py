"""Campaign A (EXPLORED tooling, lead): a general form of Djematene's discriminant obstruction for a
fixed-point-free automorphism sigma of prime order p of a strongly regular graph srg(v,k,lam,mu) with
integral eigenvalues k > r > s.  Notation: m = v/p orbits; Q = quotient matrix (integer), M = sum_b zeta^b A_b
(Hermitian over O_K, K = Q(zeta_p)).  For an eigenvalue th in {r, s} (other eigenvalue th2) with
p not dividing (k-th)(th-th2):
  (R)  rank equality a = a' (rank of ker(Q - th) over Z equals rank of ker(M - th) over O_K), hence p | f_th,
       and every sigma^b (b != 0) moves exactly c = mu*m/(k - th) orbit representatives to neighbours:
       sum_U A_b[U,U] = c for all b != 0, so tr Q = (p-1) c;
  (D)  with d = disc ker_Z(Q - th) and d' = disc of the Hermitian lattice ker_{O_K}(M - th) (p <= 19, O_K a PID):
       Legendre(d / p) = N_{K+/Q}(d') mod p, d | ((k-th)(th-th2))^a, N(d') | (th-th2)^{a(p-1)/2}, and for every
       prime l | m with l not dividing (m/g)(th-th2), g = gcd(m, k-th): v_l(d) = v_l(m) (mod 2).
`test_params` lists, per (p, th), whether these conditions can hold; `check_graph` computes a, a', d, N(d')
on a real graph and verifies the predicted relations (validation on known graphs)."""
import itertools
import math
from math import gcd, isqrt


def primes_of(n):
    n, out, q = abs(n), [], 2
    while q * q <= n:
        if n % q == 0:
            out.append(q)
            while n % q == 0:
                n //= q
        q += 1
    if n > 1:
        out.append(n)
    return out


def vval(n, l):
    c = 0
    while n % l == 0:
        n //= l
        c += 1
    return c


def legendre(a, p):
    a %= p
    if a == 0:
        return 0
    return 1 if pow(a, (p - 1) // 2, p) == 1 else -1


def eigen(v, k, lam, mu):
    disc = (mu - lam) ** 2 + 4 * (k - mu)
    sq = isqrt(disc)
    if sq * sq != disc or (-(mu - lam) + sq) % 2:
        return None
    r, s = (-(mu - lam) + sq) // 2, (-(mu - lam) - sq) // 2
    fr_num = -(k + (v - 1) * s)
    if fr_num % (r - s):
        return None
    fr = fr_num // (r - s)
    return r, s, fr, v - 1 - fr


def test_params(v, k, lam, mu, pmax=19):
    """Per prime p | v and th in {r, s}: 'n/a' (p | (k-th)(th-th2)), 'R' (rank/trace condition fails),
    'D' (discriminant condition fails), 'ok'.  p = 2 gets only (R)."""
    e = eigen(v, k, lam, mu)
    if e is None:
        return None
    r, s, fr, fs = e
    out = {}
    for p in primes_of(v):
        m = v // p
        for th, th2, f in ((r, s, fr), (s, r, fs)):
            key = (p, th)
            if ((k - th) * (th - th2)) % p == 0:
                out[key] = ("n/a", "")
                continue
            # (R)
            if f % p:
                out[key] = ("R", f"p does not divide f_th = {f}")
                continue
            a = f // p
            if (mu * m) % (k - th):
                out[key] = ("R", f"(k-th) = {k - th} does not divide mu*m = {mu * m}")
                continue
            c = mu * m // (k - th)
            if c > m:
                out[key] = ("R", f"c = {c} > m = {m}")
                continue
            trQ = (p - 1) * c
            a_th_from_trace_num = trQ - k - (m - 1) * th2
            if a_th_from_trace_num % (th - th2) or a_th_from_trace_num // (th - th2) != a:
                out[key] = ("R", f"tr Q = {trQ} gives a = {a_th_from_trace_num}/{th - th2}, expected f/p = {a}")
                continue
            if p == 2 or p > pmax:
                out[key] = ("ok", f"a = {a}, c = {c} (no D test for p = {p})")
                continue
            # (D)
            g = gcd(m, k - th)
            cW = (m // g) * (th - th2)
            Lq = set(primes_of((k - th) * (th - th2)))
            forced, free_nonsq, parity_fail = 1, False, None
            for l in primes_of(m):
                if cW % l:
                    if l not in Lq or a == 0:
                        if vval(m, l) % 2:
                            parity_fail = l
                    else:
                        forced *= legendre(l, p) ** vval(m, l)
            if a > 0:
                for l in Lq:
                    if not (l in primes_of(m) and cW % l):
                        if legendre(l, p) == -1:
                            free_nonsq = True
            if parity_fail:
                out[key] = ("D", f"v_{parity_fail}(m) odd but {parity_fail} cannot divide d")
                continue
            chi_d = {1, -1} if free_nonsq else {forced}
            # possible N(d') mod p: subgroup generated by primes of (th - th2), intersected with {+-1}
            gens = [q % p for q in primes_of(th - th2)] if a > 0 else []
            reach, frontier = {1}, [1]
            while frontier:
                x = frontier.pop()
                for q in gens:
                    y = x * q % p
                    if y not in reach:
                        reach.add(y)
                        frontier.append(y)
            chi_dp = {1 if x == 1 else -1 for x in reach if x in (1, p - 1)}
            if not (chi_d & chi_dp):
                out[key] = ("D", f"Legendre(d/p) in {sorted(chi_d)} but N(d') mod p in {sorted(chi_dp)}")
            else:
                out[key] = ("ok", f"a = {a}, c = {c}, chi(d) in {sorted(chi_d)}, chi(d') in {sorted(chi_dp)}")
    return {"r": r, "s": s, "f": (fr, fs), "tests": out}


