def int_kernel(A, ncols):
    M = [row[:] for row in A]
    U = [[int(i == j) for j in range(ncols)] for i in range(ncols)]

    def col_sub(j, j0, q):
        for row in M:
            row[j] -= q * row[j0]
        for row in U:
            row[j] -= q * row[j0]

    def col_swap(a, b):
        for row in M:
            row[a], row[b] = row[b], row[a]
        for row in U:
            row[a], row[b] = row[b], row[a]

    piv = 0
    for i in range(len(M)):
        while True:
            nz = [j for j in range(piv, ncols) if M[i][j] != 0]
            if len(nz) <= 1:
                break
            j0 = min(nz, key=lambda j: abs(M[i][j]))
            for j in nz:
                if j != j0:
                    col_sub(j, j0, M[i][j] // M[i][j0])
        nz = [j for j in range(piv, ncols) if M[i][j] != 0]
        if nz:
            col_swap(nz[0], piv)
            piv += 1
    return [[U[i][j] for i in range(ncols)] for j in range(piv, ncols)]


def lll_columns(vecs):
    """Size-reduce the kernel basis a little (keeps the lattice) to keep numbers small."""
    return vecs


def bareiss_det(M):
    n = len(M)
    if n == 0:
        return 1
    A = [row[:] for row in M]
    sign, prev = 1, 1
    for k in range(n - 1):
        if A[k][k] == 0:
            sw = next((i for i in range(k + 1, n) if A[i][k] != 0), None)
            if sw is None:
                return 0
            A[k], A[sw] = A[sw], A[k]
            sign = -sign
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                A[i][j] = (A[i][j] * A[k][k] - A[i][k] * A[k][j]) // prev
        prev = A[k][k]
    return sign * A[n - 1][n - 1]


def check_graph(n, adj, sigma, p):
    """Compute a, a', d, N(d') for each th and verify (R) and (D) on a real graph with a fixed-point-free
    automorphism sigma of prime order p (p odd, <= 19)."""
    assert all(sigma[x] != x for x in range(n))
    reps, seen = [], set()
    for x in range(n):
        if x not in seen:
            orb = [x]
            while sigma[orb[-1]] != x:
                orb.append(sigma[orb[-1]])
            assert len(orb) == p
            seen.update(orb)
            reps.append(x)
    m = len(reps)
    powr = []
    for x in reps:
        row = [x]
        for _ in range(p - 1):
            row.append(sigma[row[-1]])
        powr.append(row)
    Ab = [[[int(powr[V][b] in adj[reps[U]]) for V in range(m)] for U in range(m)] for b in range(p)]
    k = len(adj[0])
    Q = [[sum(Ab[b][U][V] for b in range(p)) for V in range(m)] for U in range(m)]
    lam = len(adj[0] & adj[next(iter(adj[0]))])
    mu = len(adj[0] & adj[next(y for y in range(1, n) if y not in adj[0])])
    r, s, fr, fs = eigen(n, k, lam, mu)
    cb = [sum(Ab[b][U][U] for U in range(m)) for b in range(p)]
    res = {"v": n, "k": k, "lam": lam, "mu": mu, "p": p, "m": m, "r": r, "s": s, "c_b": cb}
    # M entries in the power basis 1, z, ..., z^(p-2): z^(p-1) = -(1 + ... + z^(p-2))
    def ent(U, V):
        coef = [0] * (p - 1)
        for b in range(p):
            if Ab[b][U][V]:
                if b < p - 1:
                    coef[b] += 1
                else:
                    for i in range(p - 1):
                        coef[i] -= 1
        return coef

    def mulmat(coef):
        # matrix of multiplication by z = sum coef_i zeta^i on the power basis
        cols = []
        for j in range(p - 1):
            prod = [0] * p
            for i in range(p - 1):
                prod[(i + j) % p] += coef[i]
            vec = [prod[t] - prod[p - 1] for t in range(p - 1)]
            cols.append(vec)
        return [[cols[j][i] for j in range(p - 1)] for i in range(p - 1)]

    E = [[ent(U, V) for V in range(m)] for U in range(m)]
    tr_form = [[(p - 1) if i == j else -1 for j in range(p - 1)] for i in range(p - 1)]
    for th, th2 in ((r, s), (s, r)):
        rec = {}
        QmI = [[Q[i][j] - (th if i == j else 0) for j in range(m)] for i in range(m)]
        L = int_kernel(QmI, m)
        a = len(L)
        d = bareiss_det([[sum(x * y for x, y in zip(u, w)) for w in L] for u in L])
        D = p - 1
        R = [[0] * (D * m) for _ in range(D * m)]
        for U in range(m):
            for V in range(m):
                coef = E[U][V][:]
                if U == V:
                    coef[0] -= th
                blk = mulmat(coef)
                for i in range(D):
                    for j in range(D):
                        R[D * U + i][D * V + j] = blk[i][j]
        Lp = int_kernel(R, D * m)
        assert len(Lp) % D == 0
        ap = len(Lp) // D

        def form(u, w):
            return sum(u[D * U + i] * tr_form[i][j] * w[D * U + j] for U in range(m) for i in range(D) for j in range(D))

        detZ = bareiss_det([[form(u, w) for w in Lp] for u in Lp])
        base = p ** ((p - 2) * ap)
        assert detZ % base == 0
        nd2 = detZ // base
        nd = isqrt(nd2)
        assert nd * nd == nd2
        rec.update({"a": a, "a_prime": ap, "d": d, "N_dprime": nd})
        applicable = ((k - th) * (th - th2)) % p != 0
        rec["applicable"] = applicable
        if applicable:
            rec["R_rank_equal"] = a == ap
            rec["R_cb_constant"] = len(set(cb[1:])) == 1 and cb[1] * (k - th) == mu * m
            rec["D_legendre"] = legendre(d, p) == (1 if nd % p == 1 else (-1 if nd % p == p - 1 else 0))
            rec["D_d_divides"] = ((k - th) * (th - th2)) ** a % d == 0
            rec["D_Nd_divides"] = (abs(th - th2) ** (a * (p - 1) // 2)) % nd == 0
            g = gcd(m, k - th)
            cW = (m // g) * (th - th2)
            rec["D_parity"] = all(vval(d, l) % 2 == vval(m, l) % 2 for l in primes_of(m) if cW % l)
        res[f"th={th}"] = rec
    return res


def triangular(n):
    pairs = list(itertools.combinations(range(n), 2))
    idx = {pr: i for i, pr in enumerate(pairs)}
    adj = [set() for _ in pairs]
    for i, a in enumerate(pairs):
        for j, b in enumerate(pairs):
            if i != j and len(set(a) & set(b)) == 1:
                adj[i].add(j)
    return pairs, idx, adj


def tri_sigma(n, p):
    """Product of p-cycles on 0..n-1 fixing at most one point (n = 0 or 1 mod p), acting on pairs."""
    assert n % p in (0, 1)
    perm = list(range(n))
    for start in range(0, n - n % p, p):
        for t in range(p):
            perm[start + t] = start + (t + 1) % p
    pairs, idx, adj = triangular(n)
    sig = [idx[tuple(sorted((perm[a], perm[b])))] for a, b in pairs]
    return len(pairs), adj, sig


