"""Referee's independent re-implementation for the discriminant-obstruction note.

Methodological independence from campaign_A/obstruction.py:
- integral kernel: sympy nullspace over Q + lattice saturation index via gcd of
  maximal minors; discriminant d = det(V^T V) / g^2 (no basis needed).
- O_K objects: own regular representation over Z^{(p-1)} (polynomial
  multiplication mod cyclotomic, written here); trace-form disc for N(d')^2.
- cor:test: reimplemented from the note's statement, not from test_params.
- Brouwer table: own parser.
Run: .venv/bin/python referee.py [part]
"""
