# ---------------------------------------------------------------- utilities

def primes_of(n):
    n, out, q = abs(n), [], 2
    while q * q <= n:
        if n % q == 0:
            out.append(q)
            while n % q == 0:
                n //= q
        q += 1
    if n > 1:
        out.append(n)
    return out


def vval(n, l):
    c = 0
    while n % l == 0:
        n //= l
        c += 1
    return c


def legendre(a, p):
    a %= p
    if a == 0:
        return 0
    return 1 if pow(a, (p - 1) // 2, p) == 1 else -1


def eigen(v, k, lam, mu):
    disc = (mu - lam) ** 2 + 4 * (k - mu)
    sq = isqrt(disc)
    if sq * sq != disc or (-(mu - lam) + sq) % 2:
        return None
    r, s = (-(mu - lam) + sq) // 2, (-(mu - lam) - sq) // 2
    fr_num = -(k + (v - 1) * s)
    if fr_num % (r - s):
        return None
    return r, s, fr_num // (r - s), v - 1 - fr_num // (r - s)


# ------------------------------------------------------- integer kernel & d

def rational_kernel_cols(A):
    """List of integer column vectors spanning ker_Q A (sympy fraction-free
    nullspace, denominators cleared)."""
    ns = Matrix(A).nullspace()
    cols = []
    for v in ns:
        den = 1
        for x in v:
            den = den * x.q // gcd(den, x.q)
        w = [int(x * den) for x in v]
        g = 0
        for x in w:
            g = gcd(g, abs(x))
        cols.append([x // g for x in w])
    return cols


def sat_index(cols):
    """Index of the lattice generated by cols in its saturation Z^n cap span:
    product of the nonzero Smith normal form invariant factors."""
    if not cols:
        return 1
    n, a = len(cols[0]), len(cols)
    V = Matrix(n, a, lambda i, j: cols[j][i])
    S = smith_normal_form(V, domain=ZZ)
    g = 1
    for i in range(min(n, a)):
        g *= abs(int(S[i, i]))
    return g


def sat_discriminant(cols):
    """disc of the saturated lattice Z^n cap span(cols): det(V^T V)/g^2."""
    if not cols:
        return 1
    a = len(cols)
    V = Matrix(len(cols[0]), a, lambda i, j: cols[j][i])
    g = sat_index(cols)
    detG = int((V.T * V).det())
    assert detG % (g * g) == 0
    return detG // (g * g)


# ------------------------------------------------------- cyclotomic regular rep

def mulmod(u, w, p):
    """Product of two elements of O_K in basis 1, z, .., z^{p-2} (ints).
    Polynomial mult, wrap exponents via z^p = 1, then z^{p-1} = -(1+..+z^{p-2})."""
    d = p - 1
    prod = [0] * (2 * p - 1)
    for i in range(d):
        for j in range(d):
            prod[i + j] += u[i] * w[j]
    full = [0] * p
    for e in range(len(prod)):
        full[e % p] += prod[e]
    return [full[t] - full[p - 1] for t in range(d)]


def mul_matrix(coef, p):
    """Matrix of multiplication by sum coef_i z^i on the power basis."""
    d = p - 1
    cols = [mulmod(coef, [int(t == j) for t in range(d)], p) for j in range(d)]
    return [[cols[j][i] for j in range(d)] for i in range(d)]


def trace_form_value(u, w, p):
    """Tr_{K/Q}(u * conj(w)) on power-basis vectors (Tr(z^i) = p-1 if i==0 mod p else -1)."""
    # conj(w): z^j -> z^{-j}; w = sum w_j z^j -> w_0 + sum_{j>0} w_j z^{p-j}
    d = p - 1
    cw = [w[0]] + [0] * (d - 1)
    for j in range(1, d):
        cw[(p - j) % p] += w[j]  # p-j in 1..d
    pr = mulmod(u, cw, p)
    return pr[0] * p - sum(pr)  # Tr = (p-1)*pr[0] - sum_{i>0} pr[i]


# ------------------------------------------------------------- graphs

def srg_params_ok(n, adj, k, lam, mu):
    for u in range(n):
        if u in adj[u] or len(adj[u]) != k:
            return False
        for v in adj[u]:
            if u not in adj[v]:
                return False
    for u, v in itertools.combinations(range(n), 2):
        c = len(adj[u] & adj[v])
        if c != (lam if u in adj[v] else mu):
            return False
    return True


def triangular(n):
    pairs = list(itertools.combinations(range(n), 2))
    idx = {pr: i for i, pr in enumerate(pairs)}
    adj = [set() for _ in pairs]
    for a, b in itertools.combinations(range(len(pairs)), 2):
        if len(set(pairs[a]) & set(pairs[b])) == 1:
            adj[a].add(b)
            adj[b].add(a)
    return len(pairs), adj


def tri_sigma(n, p):
    perm = list(range(n))
    for start in range(0, n - n % p, p):
        for t in range(p):
            perm[start + t] = start + (t + 1) % p
    pairs = list(itertools.combinations(range(n), 2))
    idx = {pr: i for i, pr in enumerate(pairs)}
    return [idx[tuple(sorted((perm[a], perm[b])))] for a, b in pairs]


def petersen():
    pairs = list(itertools.combinations(range(5), 2))
    adj = [set() for _ in pairs]
    for a, b in itertools.combinations(range(10), 2):
        if not (set(pairs[a]) & set(pairs[b])):
            adj[a].add(b)
            adj[b].add(a)
    perm5 = [1, 2, 3, 4, 0]
    idx = {pr: i for i, pr in enumerate(pairs)}
    sig = [idx[tuple(sorted((perm5[x] for x in pr)))] for pr in pairs]
    return 10, adj, sig


def gq33():
    """GQ(3,3) = srg(40,12,2,4): points = 1-dim subspaces of F_81 (deg-4 ext of F_3,
    t = root of Phi5 = t4+t3+t2+t+1, irreducible since ord_5(3) = 4); B(x,y) =
    Tr_{F81/F3}((t - t^9) x y^9) is alternating nondegenerate; sigma = mult by t
    (order 5, fpf) preserves B since t^10 = 1."""
    P3 = 3

    def mul(x, y):  # polys deg<4 over F3, mod Phi5: t4 = -(1+t+t2+t3) = 2+2t+2t2+2t3
        prod = [0] * 7
        for i in range(4):
            for j in range(4):
                prod[i + j] = (prod[i + j] + x[i] * y[j]) % 3
        for e in range(6, 3, -1):
            c = prod[e] % 3
            if c:
                for s in range(4):
                    prod[e - 4 + s] = (prod[e - 4 + s] + 2 * c) % 3
                prod[e] = 0
        return tuple(prod[:4])

    def add(x, y):
        return tuple((a + b) % 3 for a, b in zip(x, y))

    def neg(x):
        return tuple(-a % 3 for a in x)

    def powmod(x, e):
        r = (1, 0, 0, 0)
        while e:
            if e & 1:
                r = mul(r, x)
            x = mul(x, x)
            e >>= 1
        return r

    def tr(x):  # Tr_{F81/F3} = x + x^3 + x^9 + x^27, lands in F_3
        return sum(powmod(x, e)[0] for e in (1, 3, 9, 27)) % 3

    t = (0, 1, 0, 0)
    c = add(t, neg(powmod(t, 9)))
    elems = [tuple(v) for v in itertools.product(range(3), repeat=4)]
    elems.remove((0, 0, 0, 0))

    def B(x, y):
        return tr(mul(c, mul(x, powmod(y, 9)))) % 3

    # projective points: 40 pairs {x, 2x}
    pts, seen = [], set()
    for x in elems:
        if x in seen:
            continue
        seen.add(x)
        seen.add(neg(x))
        pts.append(x)
    assert len(pts) == 40
    adj = [set() for _ in pts]
    pos = {x: i for i, x in enumerate(pts)}
    for x in pts:
        for y in pts:
            if x != y and y != neg(x) and B(x, y) % 3 == 0:
                adj[pos[x]].add(pos[y])
    sig = []
    npos = {x: i for i, x in enumerate(pts)}
    inv = {}
    for x in pts:
        inv[x] = pos[x]
        inv[neg(x)] = pos[x]
    for x in pts:
        sig.append(inv[mul(t, x)])
    return 40, adj, sig, B, pts, mul, powmod


def circulant_search(v, k):
    """An srg circulant of order v, degree k (if one exists): connection set
    closed under negation.  Returns (adj, sigma) with sigma = shift by 1."""
    pairs = [p for p in range(1, v // 2 + 1)]
    selfinv = v % 2 == 0
    npair = v // 2 - (1 if selfinv else 0)
    need_pairs = k - (1 if (selfinv and k % 2) else 0)
    for combo in itertools.combinations(range(1, v // 2 + (0 if selfinv else 1)), need_pairs // 2):
        S = set()
        for x in combo:
            S.add(x)
            S.add(v - x)
        if selfinv and k % 2:
            S.add(v // 2)
        if len(S) != k:
            continue
        adj = [set() for _ in range(v)]
        for x in range(v):
            for s in S:
                adj[x].add((x + s) % v)
        # check srg: compute (k2 via lambda/mu from first nbr/non-nbr)
        if check_is_srg(adj):
            return adj, [(x + 1) % v for x in range(v)]
    return None


def check_is_srg(adj):
    n = len(adj)
    k = len(adj[0])
    if any(len(adj[u]) != k for u in range(n)):
        return None
    u, v = 0, next(iter(adj[0]))
    lam = len(adj[u] & adj[v])
    w = next(y for y in range(1, n) if y not in adj[0])
    mu = len(adj[0] & adj[w])
    return (k, lam, mu) if srg_params_ok(n, adj, k, lam, mu) else None


