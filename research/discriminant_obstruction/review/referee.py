def analyze(n, adj, sigma, p):
    """Compute a, a', d, N(d') for both theta values.  Returns dict."""
    assert all(sigma[x] != x for x in range(n)), "sigma must be fixed-point-free"
    # orbits
    reps, seen = [], set()
    for x in range(n):
        if x in seen:
            continue
        orb = [x]
        while sigma[orb[-1]] != x:
            orb.append(sigma[orb[-1]])
        assert len(orb) == p
        seen.update(orb)
        reps.append(x)
    m = len(reps)
    powr = [reps]
    # powr[U][b] = sigma^b rep_U
    powr = []
    for x in reps:
        row = [x]
        for _ in range(p - 1):
            row.append(sigma[row[-1]])
        powr.append(row)
    Ab = [[[int(powr[V][b] in adj[reps[U]]) for V in range(m)] for U in range(m)] for b in range(p)]
    Q = [[sum(Ab[b][U][V] for b in range(p)) for V in range(m)] for U in range(m)]
    cb = [sum(Ab[b][U][U] for U in range(m)) for b in range(p)]
    k = len(adj[0])
    lam = len(adj[0] & adj[next(iter(adj[0]))])
    mu = len(adj[0] & adj[next(y for y in range(1, n) if y not in adj[0])])
    r, s, fr, fs = eigen(n, k, lam, mu)
    D = p - 1
    trf = [[p - 1 if i == j else -1 for j in range(D)] for i in range(D)]
    # power-basis coordinates of each M entry (Ab[b] contributes z^b; z^{p-1} = -(1+..+z^{p-2}))
    E = {}
    for U in range(m):
        for V in range(m):
            coef = [0] * D
            for b in range(p):
                if Ab[b][U][V]:
                    if b < D:
                        coef[b] += 1
                    else:
                        for i in range(D):
                            coef[i] -= 1
            E[U, V] = coef
    out = {"v": n, "k": k, "lam": lam, "mu": mu, "p": p, "m": m, "r": r, "s": s,
           "fr": fr, "fs": fs, "c_b": cb}
    for th, th2 in ((r, s), (s, r)):
        rec = {}
        kerQ = rational_kernel_cols([[Q[i][j] - (th if i == j else 0) for j in range(m)] for i in range(m)])
        a = len(kerQ)
        d = sat_discriminant(kerQ)
        # Z^{(p-1)m} matrix of M - th
        R = [[0] * (D * m) for _ in range(D * m)]
        for U in range(m):
            for V in range(m):
                coef = E[U, V][:]
                if U == V:
                    coef[0] -= th
                blk = mul_matrix(coef, p)
                for i in range(D):
                    for j in range(D):
                        R[D * U + i][D * V + j] = blk[i][j]
        kerR = rational_kernel_cols(R)
        assert len(kerR) % D == 0, (len(kerR), D)
        ap = len(kerR) // D
        # trace-form Gram on the kernel columns (each column = concatenated m power-basis vectors)
        def tf(u, w):
            tot = 0
            for U in range(m):
                for i in range(D):
                    for j in range(D):
                        tot += u[D * U + i] * trf[i][j] * w[D * U + j]
            return tot
        G = [[tf(u, w) for w in kerR] for u in kerR]
        detG = int(Matrix(G).det())
        # the kernel vectors may generate a sublattice of index g in the saturated one
        g = sat_index(kerR)
        discZ = detG // (g * g)
        base = p ** ((p - 2) * ap)
        assert discZ % base == 0, (discZ, base)
        nd2 = discZ // base
        nd = isqrt(nd2)
        assert nd * nd == nd2, nd2
        applicable = ((k - th) * (th - th2)) % p != 0
        rec.update({"a": a, "a_prime": ap, "d": d, "N_dprime": nd, "applicable": applicable})
        if applicable:
            rec["a_eq_ap"] = a == ap
            rec["cb_const"] = len(set(cb[1:])) == 1 and cb[1] == (k - th2) // p
            rec["leg_d"] = legendre(d, p)
            rec["nd_mod_p"] = nd % p
            rec["d_div"] = ((k - th) * (th - th2)) ** a % d == 0
            rec["nd_div"] = abs(th - th2) ** (a * (p - 1) // 2) % nd == 0
            g2 = gcd(m, k - th)
            cW = (m // g2) * (th - th2)
            rec["parity_ok"] = all(vval(d, l) % 2 == vval(m, l) % 2 for l in primes_of(m) if cW % l)
        out[f"th={th}"] = rec
    return out


def my_test(v, k, lam, mu):
    """Referee's own implementation of Corollary cor:test.  Returns per (p,th)
    a verdict: 'n/a', 'R' (rank/trace obstruction), 'D' (discriminant
    obstruction), or 'ok' with a short justification."""
    e = eigen(v, k, lam, mu)
    if e is None:
        return None
    r, s, fr, fs = e
    res = {}
    for p in primes_of(v):
        m = v // p
        for th, th2, f in ((r, s, fr), (s, r, fs)):
            key = (p, th)
            if ((k - th) * (th - th2)) % p == 0:
                res[key] = ("n/a", "p | (k-th)(th-th')")
                continue
            # part (a) consequences
            if f % p:
                res[key] = ("R", f"p does not divide f_th={f}")
                continue
            a = f // p
            if (k - th2) % p or (mu * m) % (k - th) or mu * m // (k - th) != (k - th2) // p:
                # c = mu m/(k-th) must be the integer (k-th')/p; check both forms
                if (mu * m) % (k - th):
                    res[key] = ("R", "trace: (k-th) does not divide mu*m")
                    continue
            c = mu * m // (k - th)
            if c > m or c < 0:
                res[key] = ("R", f"c={c} not in [0,m]")
                continue
            # consistency of a with tr Q = (p-1)c: Q has eigenvalues k once,
            # th with multiplicity a, th2 with multiplicity m-1-a, so
            # tr Q = k + a*th + (m-1-a)*th2 must equal (p-1)c.
            num = (p - 1) * c - k - (m - 1) * th2
            if (th - th2) == 0 or num % (th - th2) or num // (th - th2) != a:
                res[key] = ("R", f"trace gives a = {num}/{th - th2} != {a}")
                continue
            if p == 2 or p > 19:
                res[key] = ("ok", "no D test")
                continue
            # part (d) + (c)
            g = gcd(m, k - th)
            alpha_th = (m // g) * (th - th2)
            S = set(primes_of((k - th) * (th - th2)))
            covered = [l for l in primes_of(m) if alpha_th % l != 0]
            # parity obstruction: covered l not in S forces v_l(d) = 0
            bad = [l for l in covered if (l not in S or a == 0) and vval(m, l) % 2]
            if bad:
                res[key] = ("D", f"v_{bad[0]}(m) odd but {bad[0]} cannot divide d")
                continue
            forced = 1
            for l in covered:
                if l in S and a > 0:
                    forced *= legendre(l, p) ** (vval(m, l) % 2)
            free = any(legendre(l, p) == -1 for l in S if l not in covered and a > 0)
            chi_d = {1, -1} if free else {forced}
            # chi(d') side: N(d') | |th-th2|^{a(p-1)/2}, N(d') > 0, N(d') == +-1 mod p
            if a == 0:
                chi_dp = {1}
            else:
                gens = {q % p for q in primes_of(th - th2)}
                reach, front = {1}, [1]
                while front:
                    x = front.pop()
                    for q in gens:
                        y = x * q % p
                        if y not in reach:
                            reach.add(y)
                            front.append(y)
                chi_dp = {1 if x == 1 else -1 for x in reach & {1, p - 1}}
            if chi_d & chi_dp:
                res[key] = ("ok", f"chi_d={sorted(chi_d)} chi_dp={sorted(chi_dp)}")
            else:
                res[key] = ("D", f"chi_d in {sorted(chi_d)} vs chi_dp in {sorted(chi_dp)}")
    return res
